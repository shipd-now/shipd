#!/usr/bin/env python3
"""harness_generate — dialect rendering and the harness file surfaces.

The registry (``harness_registry``) declares *where* a harness wants its
command files and *how* it wants them labelled; the body engine
(``harness_bodies``) produces *what* goes in them. This module is the join:
it turns an ``(entry, command)`` pair into the exact bytes of one generated
file, and into the exact path that file takes in a repository or in the
user's home.

Two ownership rules make the writing surface safe to automate. Every
generated file's first body line — after the frontmatter block, or after the
markdown header block — is :data:`MARKER`, so a later action can tell the
files it wrote from the user's own. And every managed path derives from
registry data alone, so nothing here can address a directory the registry
does not name.

Stdlib-only Python 3, per the engine's constitution.
"""

import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import harness_bodies  # noqa: E402
import harness_registry  # noqa: E402
import spec_common  # noqa: E402

# The ownership marker. A generated file carries it; a file without it was
# not written here and is never rewritten or deleted without ``--force``.
MARKER = "<!-- generated by shipd harness; do not edit -->"

# The two surface modes: repo-level files under a root, and the user-global
# directories the registry's ``user_dir`` names.
REPO_MODE = "repo"
USER_MODE = "user"
MODES = (REPO_MODE, USER_MODE)

# The refs root, relative to the content directory in repo mode and fixed in
# user mode. Both are also the literal text substituted for a body's
# ``{refs}`` placeholder, so a generated file names a path that survives
# being committed and read on another machine.
REFS_SUBDIR = ("harness", "references")
USER_REFS = "~/.shipd/harness/references"

# The registry feature whose harnesses get the fallback reference files. A
# harness declaring it renders bodies that point at ``{refs}``; one that does
# not renders the inline ``else`` branch and needs no files.
FILE_REFERENCES = "file-references"

# The fixed value table behind the ``yaml`` dialect's frontmatter. A field a
# harness declares but this table gives no value for — ``allowed-tools``, the
# only one today — is *omitted* from the rendered frontmatter rather than
# emitted empty: a harness reads an absent field as "no restriction", while
# an empty one can read as "nothing allowed".
#
# ``name``/``id``/``title`` are the command's namespaced id and
# ``description`` is the body template's own declared description, so both
# are computed rather than tabulated; everything below is a constant.
FIXED_FRONTMATTER = {
    "category": "shipd",
    "tags": "shipd",
    "invokable": "true",
    "argument-hint": "[input]",
}

# Characters that, leading a YAML scalar, make it something other than plain
# text — an indicator, a flow collection, an anchor, a quoted string.
_LEADING_INDICATORS = "-?:,[]{}#&*!|>'\"%@`"


def command_id(command):
    """``command``'s namespaced id — the name every harness sees it under."""
    return "shipd-%s" % command


def yaml_scalar(value):
    """``value`` as a YAML scalar, double-quoted when plain text would not
    round-trip.

    Quoting triggers on a colon or a ``#`` anywhere (either can end a plain
    scalar, and the descriptions carry ``/s:`` command names), on a leading
    indicator character, on surrounding whitespace, on a newline, and on
    emptiness. Everything else — including the bare ``true`` the
    ``invokable`` field needs to stay a boolean — is emitted as written.
    """
    text = str(value)
    if (text == "" or text != text.strip() or text[0] in _LEADING_INDICATORS
            or ":" in text or "#" in text or "\n" in text):
        escaped = (text.replace("\\", "\\\\").replace('"', '\\"')
                   .replace("\n", "\\n"))
        return '"%s"' % escaped
    return text


def frontmatter_value(field, command, base_dir=None):
    """The value the fixed table gives ``field`` for ``command``, or ``None``
    when it declares none — such a field is omitted from the render."""
    if field in ("name", "id", "title"):
        return command_id(command)
    if field == "description":
        return harness_bodies.description(command, base_dir)
    return FIXED_FRONTMATTER.get(field)


def _yaml_head(entry, command, base_dir):
    """The ``---``-delimited frontmatter block, carrying exactly the entry's
    declared fields, in the order it declares them."""
    lines = ["---"]
    for field in entry["frontmatter"]:
        value = frontmatter_value(field, command, base_dir)
        if value is None:
            continue
        lines.append("%s: %s" % (field, yaml_scalar(value)))
    lines.append("---")
    return "".join("%s\n" % line for line in lines)


def _headers_head(command, base_dir):
    """The ``markdown-headers`` dialect's block: the heading, the description
    line, and a blank — the same two facts the frontmatter carries, for a
    harness that reads prose rather than metadata."""
    description = harness_bodies.description(command, base_dir) or ""
    return "# %s\n%s\n\n" % (command_id(command), description)


def render(entry, command, refs=None, base_dir=None):
    """The full text of ``command``'s generated file for harness ``entry``.

    The dialect's metadata block comes first, then :data:`MARKER`, then the
    body scaled to the entry's declared features with ``{refs}`` resolved to
    ``refs``. Raises ``ValueError`` for a dialect with no renderer — no
    harness with a surface declares one today, and a silent empty file would
    be worse than a refusal.
    """
    dialect = entry["dialect"]
    if dialect == "yaml":
        head = _yaml_head(entry, command, base_dir)
    elif dialect == "markdown-headers":
        head = _headers_head(command, base_dir)
    else:
        raise ValueError("no renderer for the %r dialect (harness %r)"
                         % (dialect, entry["id"]))
    body = harness_bodies.render(command, entry["features"], refs_dir=refs,
                                 base_dir=base_dir)
    return "%s%s\n\n%s" % (head, MARKER, body)


# ---------------------------------------------------------------------------
# Surfaces
# ---------------------------------------------------------------------------


def repo_relpath(entry, command):
    """``command``'s generated file for ``entry``, relative to a repository
    root, or ``None`` when the harness has no per-repo surface."""
    pattern = entry["repo_pattern"]
    if pattern is None:
        return None
    return os.path.normpath(pattern.format(command=command))


def user_basename(entry, command):
    """The filename ``command`` takes in a user-global directory: the repo
    pattern's own basename where there is one — Claude Code's pattern already
    namespaces under ``shipd/``, so its files stay ``<command>.md`` — and the
    namespaced default otherwise."""
    pattern = entry["repo_pattern"]
    if pattern is None:
        return "%s.md" % command_id(command)
    return os.path.basename(pattern.format(command=command))


def user_path(entry, command):
    """``command``'s generated file for ``entry`` in the user-global surface,
    absolute with ``~`` expanded, or ``None`` when it has no ``user_dir``."""
    directory = entry["user_dir"]
    if directory is None:
        return None
    return os.path.join(os.path.expanduser(directory),
                        user_basename(entry, command))


def has_surface(entry, mode):
    """Whether ``entry`` has any generated-file surface in ``mode``."""
    key = "user_dir" if mode == USER_MODE else "repo_pattern"
    return entry[key] is not None


def target_path(entry, command, mode, root=None):
    """The absolute path ``command``'s file takes for ``entry`` in ``mode``,
    or ``None`` when the harness has no surface there."""
    if mode == USER_MODE:
        return user_path(entry, command)
    relative = repo_relpath(entry, command)
    if relative is None:
        return None
    return os.path.join(os.path.abspath(root), relative)


def _content_dirname(root):
    """``root``'s content-directory name as its layered config resolves it —
    a repo renaming ``.shipd`` gets its references under that name too.
    Raises ``spec_common.ConfigError`` for an unusable configuration."""
    config, _provenance = spec_common.resolve_config(root)
    return spec_common.specs_dirname(config)


def refs_label(mode, root=None):
    """The text a generated body's ``{refs}`` placeholder becomes: the refs
    root as a path the file can still name after it is committed and read
    elsewhere — repo-relative in repo mode, ``~``-rooted in user mode."""
    if mode == USER_MODE:
        return USER_REFS
    return "/".join((_content_dirname(root),) + REFS_SUBDIR)


def refs_root(mode, root=None):
    """The absolute directory the fallback reference files are written to."""
    if mode == USER_MODE:
        return os.path.expanduser(USER_REFS)
    return os.path.join(os.path.abspath(root), _content_dirname(root),
                        *REFS_SUBDIR)


def ids_with_surface(mode):
    """Every harness id with a generated-file surface in ``mode``, in
    registry order."""
    return tuple(entry["id"] for entry in harness_registry.HARNESSES
                 if has_surface(entry, mode))


def command_paths(entry, mode, root=None, base_dir=None):
    """Every generated command-file path for ``entry`` in ``mode``, empty
    when it has no surface there."""
    if not has_surface(entry, mode):
        return []
    return [target_path(entry, command, mode, root)
            for command in harness_bodies.commands(base_dir)]


def reference_paths(mode, root=None, base_dir=None):
    """Every fallback reference file's path under the refs root."""
    directory = refs_root(mode, root)
    return [os.path.join(directory, "%s.md" % command)
            for command in harness_bodies.commands(base_dir)
            if harness_bodies.reference(command, base_dir) is not None]


def display(path, mode, root=None):
    """``path`` as a report names it: relative to the repository root in repo
    mode, ``~``-abbreviated in user mode — never the caller's absolute temp
    path in one report and a tidy relative one in the next."""
    if mode == REPO_MODE and root is not None:
        return os.path.relpath(path, os.path.abspath(root))
    home = os.path.expanduser("~")
    if path == home or path.startswith(home + os.sep):
        return "~" + path[len(home):]
    return path


# ---------------------------------------------------------------------------
# Payloads
# ---------------------------------------------------------------------------


def _reference_payloads(mode, root, base_dir):
    """``[(path, text)]`` for the fallback reference files. They carry the
    ownership marker too — they are generated files, so ``remove`` must be
    able to tell them from a reference the user wrote by hand."""
    directory = refs_root(mode, root)
    payloads = []
    for command in harness_bodies.commands(base_dir):
        text = harness_bodies.reference(command, base_dir)
        if text is None:
            continue
        payloads.append((os.path.join(directory, "%s.md" % command),
                         "%s\n\n%s" % (MARKER, text)))
    return payloads


def _command_payloads(entry, mode, root, base_dir, label):
    """``[(path, text)]`` for one harness's own command files."""
    return [(target_path(entry, command, mode, root),
             render(entry, command, refs=label, base_dir=base_dir))
            for command in harness_bodies.commands(base_dir)]


def planned(entries, mode, root=None, base_dir=None):
    """``(payloads, skipped)`` for ``entries`` in ``mode``.

    ``payloads`` is ``[(absolute path, text)]`` covering every selected
    harness's command files plus — once, since the refs root is shared — the
    fallback reference files, when any selected harness declares
    ``file-references``. ``skipped`` holds the ids with no surface in this
    mode; they are reported, never an error.
    """
    payloads = []
    skipped = []
    label = None
    wants_references = False
    for entry in entries:
        if not has_surface(entry, mode):
            skipped.append(entry["id"])
            continue
        if label is None:
            label = refs_label(mode, root)
        payloads.extend(_command_payloads(entry, mode, root, base_dir, label))
        wants_references = (wants_references
                            or FILE_REFERENCES in entry["features"])
    if wants_references:
        payloads.extend(_reference_payloads(mode, root, base_dir))
    return payloads, skipped


# ---------------------------------------------------------------------------
# Ownership and the file operations
# ---------------------------------------------------------------------------


def _read_bytes(path):
    """``path``'s bytes, or ``None`` when it does not exist or cannot be
    read — an unreadable target is never treated as one this install owns."""
    try:
        with open(path, "rb") as handle:
            return handle.read()
    except OSError:
        return None


def owned(path):
    """Whether ``path`` exists and carries the ownership marker."""
    data = _read_bytes(path)
    if data is None:
        return False
    try:
        return MARKER in data.decode("utf-8")
    except UnicodeDecodeError:
        return False


def foreign(path):
    """Whether ``path`` exists but was not written here — the one state the
    actions refuse to act on without ``--force``."""
    return os.path.exists(path) and not owned(path)


def _atomic_write(path, data):
    """Write ``data`` to ``path`` through a same-directory temp file and a
    rename, creating parents — an interrupted run can leave a stray temp file
    but never a half-written command file in the user's repository."""
    directory = os.path.dirname(os.path.abspath(path))
    os.makedirs(directory, exist_ok=True)
    handle, tmp = tempfile.mkstemp(dir=directory, prefix=".shipd-harness-")
    try:
        with os.fdopen(handle, "wb") as fh:
            fh.write(data)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except OSError:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def _boundaries(mode, root=None):
    """The directories pruning stops at and never removes: the surface's own
    root, and the shipd content directory — an empty ``.shipd/`` is part of
    the repository's shape, not litter this action left behind."""
    if mode == USER_MODE:
        return {os.path.expanduser("~"),
                os.path.dirname(os.path.dirname(refs_root(USER_MODE)))}
    base = os.path.abspath(root)
    return {base, os.path.join(base, _content_dirname(root))}


def _prune(directory, boundaries):
    """Remove ``directory`` and each now-empty parent, stopping at a
    boundary, at a directory still holding anything, and at the filesystem
    root."""
    current = os.path.abspath(directory)
    while current not in boundaries:
        try:
            os.rmdir(current)
        except OSError:
            return
        parent = os.path.dirname(current)
        if parent == current:
            return
        current = parent


def add(entries, mode, root=None, force=False, base_dir=None):
    """Write every selected harness's files. Returns ``(lines, error)``:
    ``error`` is a single reason string when a target this install does not
    own stands in the way — and then nothing at all was written, so a refusal
    never leaves a half-installed surface behind."""
    payloads, skipped = planned(entries, mode, root, base_dir)
    lines = ["skipped %s (no %s surface)" % (harness_id, mode)
             for harness_id in skipped]
    if not force:
        blocked = [path for path, _text in payloads if foreign(path)]
        if blocked:
            return [], ("%s: not written by shipd harness (no ownership "
                        "marker) — pass --force to overwrite %s"
                        % (", ".join(display(path, mode, root)
                                     for path in blocked),
                           "them" if len(blocked) > 1 else "it"))
    current = 0
    for path, text in payloads:
        data = text.encode("utf-8")
        # Byte-compare first: an unchanged re-run must not even touch an
        # mtime, which is what makes `add` idempotent for a watcher.
        if _read_bytes(path) == data:
            current += 1
            continue
        _atomic_write(path, data)
        lines.append("wrote %s" % display(path, mode, root))
    if current:
        lines.append("%d file%s already current"
                     % (current, "" if current == 1 else "s"))
    if not payloads:
        lines.append("nothing to write: no %s surface among the selected "
                     "harnesses" % mode)
    return lines, None


def _references_still_wanted(selected, mode, root, base_dir):
    """Whether a harness *outside* ``selected`` still has generated files on
    disk and declares ``file-references`` — the refs root is shared, so it
    only goes when the last of its readers does."""
    chosen = {entry["id"] for entry in selected}
    for entry in harness_registry.HARNESSES:
        if entry["id"] in chosen or FILE_REFERENCES not in entry["features"]:
            continue
        if any(os.path.exists(path) for path
               in command_paths(entry, mode, root, base_dir)):
            return True
    return False


def remove(entries, mode, root=None, force=False, base_dir=None):
    """Delete every selected harness's generated files, and the shared
    reference files once nothing else reads them. Returns ``(lines, error)``
    on the same contract as :func:`add`."""
    candidates = []
    lines = []
    for entry in entries:
        if not has_surface(entry, mode):
            lines.append("skipped %s (no %s surface)" % (entry["id"], mode))
            continue
        candidates.extend(command_paths(entry, mode, root, base_dir))
    if (candidates
            and not _references_still_wanted(entries, mode, root, base_dir)):
        candidates.extend(reference_paths(mode, root, base_dir))

    if not force:
        blocked = [path for path in candidates if foreign(path)]
        if blocked:
            return [], ("%s: not written by shipd harness (no ownership "
                        "marker) — pass --force to delete %s"
                        % (", ".join(display(path, mode, root)
                                     for path in blocked),
                           "them" if len(blocked) > 1 else "it"))

    emptied = set()
    removed = 0
    for path in candidates:
        if not os.path.exists(path):
            continue
        os.remove(path)
        emptied.add(os.path.dirname(os.path.abspath(path)))
        removed += 1
        lines.append("removed %s" % display(path, mode, root))
    boundaries = _boundaries(mode, root)
    # Deepest first, so a parent is considered only after its children are.
    for directory in sorted(emptied, key=len, reverse=True):
        _prune(directory, boundaries)
    if not removed:
        lines.append("nothing to remove: no generated harness files found")
    return lines, None


# ---------------------------------------------------------------------------
# Status
# ---------------------------------------------------------------------------


def _entry_state(entry, mode, root, base_dir):
    """``(state, detail, expected, present)`` for one harness's surface.

    Presence is decided on the harness's *own* command files: the reference
    files live in a shared root, so another harness having installed them
    must not make this one look partly installed. They still count toward
    currency — an installed harness whose references have drifted is stale.
    """
    label = refs_label(mode, root)
    payloads = _command_payloads(entry, mode, root, base_dir, label)
    references = (_reference_payloads(mode, root, base_dir)
                  if FILE_REFERENCES in entry["features"] else [])
    expected = len(payloads)

    present = [(path, text) for path, text in payloads
               if os.path.exists(path)]
    blocked = [path for path, _text in present + references
               if os.path.exists(path) and not owned(path)]
    if blocked:
        return ("foreign",
                "%s exists without the ownership marker"
                % display(blocked[0], mode, root), expected, len(present))
    if not present:
        return "absent", "not installed", expected, 0

    missing = expected - len(present)
    differing = [path for path, text in present
                 if _read_bytes(path) != text.encode("utf-8")]
    stale_references = [path for path, text in references
                        if _read_bytes(path) != text.encode("utf-8")]
    if not missing and not differing and not stale_references:
        return ("installed", "%d files, byte-current" % expected,
                expected, len(present))
    reasons = []
    if missing:
        reasons.append("%d missing" % missing)
    if differing:
        reasons.append("%d differing" % len(differing))
    if stale_references:
        reasons.append("%d reference file%s missing or differing"
                       % (len(stale_references),
                          "" if len(stale_references) == 1 else "s"))
    return ("stale",
            "%d files, %s — `shipd harness add` refreshes them"
            % (expected, " and ".join(reasons)), expected, len(present))


def status(entries, mode, root=None, base_dir=None):
    """``{harness id: record}`` in the order ``entries`` gives, each record
    carrying ``state``, ``detail``, ``surface``, ``expected`` and
    ``present``. Reads only — nothing here creates or modifies a file."""
    report = {}
    for entry in entries:
        if not has_surface(entry, mode):
            report[entry["id"]] = {
                "state": "skipped",
                "detail": "no %s surface" % mode,
                "surface": None,
                "expected": 0,
                "present": 0,
            }
            continue
        state, detail, expected, present = _entry_state(
            entry, mode, root, base_dir)
        first = command_paths(entry, mode, root, base_dir)[0]
        report[entry["id"]] = {
            "state": state,
            "detail": detail,
            "surface": display(os.path.dirname(first), mode, root),
            "expected": expected,
            "present": present,
        }
    return report
