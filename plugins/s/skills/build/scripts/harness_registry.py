def get(harness_id):
    """The entry ``harness_id`` names, or ``None`` when no entry has that id."""
    for entry in HARNESSES:
        if entry["id"] == harness_id:
            return entry
    return None


def agent_surface(harness_id):
    """The entry's ``agent`` member — its agent-file surface — or ``None``.

    ``None`` means the harness declares no agent surface: either it is not a
    registry entry, or it declares no ``subagents`` feature.
    """
    entry = get(harness_id)
    return entry["agent"] if entry is not None else None


def ids():
    """Every harness id, in registry order."""
    return tuple(entry["id"] for entry in HARNESSES)
